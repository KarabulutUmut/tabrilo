using System.Diagnostics;
using System.IO;
using Microsoft.Win32;
using Tabrilo.Core;
using Tabrilo.Windows;

internal static class InstalledUpdate
{
    private static string identity = "";
    private static string Install => Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Programs", identity);
    private static string Settings => Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), identity);

    public static async Task RunAsync(string oldInstaller, string newInstaller, string evidence)
    {
        if (!IsTestInstaller(oldInstaller) || !IsTestInstaller(newInstaller))
            throw new ArgumentException("Use separate installers generated by package.ps1 -IsolatedTest.");
        identity = FileVersionInfo.GetVersionInfo(oldInstaller).FileDescription!.Split(' ')[0];
        if (!System.Text.RegularExpressions.Regex.IsMatch(identity, @"^Tabrilo-Isolated(-[0-9a-f]{12})?$") ||
            !FileVersionInfo.GetVersionInfo(newInstaller).FileDescription!.StartsWith(identity + " ", StringComparison.Ordinal))
            throw new ArgumentException("Both installers must share an isolated identity.");
        if (Registry.GetValue(@"HKEY_CURRENT_USER\Software\" + identity, "Version", null) is not null)
            throw new InvalidOperationException("Remove the existing Tabrilo-Isolated test installation first.");
        if (Directory.Exists(Settings) || Directory.Exists(Install))
            throw new InvalidOperationException("Use a fresh isolated test profile.");
        var oldVersion = InstallerVersion(oldInstaller);
        var newVersion = InstallerVersion(newInstaller);
        if (newVersion <= oldVersion) throw new ArgumentException("The new installer must upgrade the old version.");

        var oldOffice = HasOffice(oldInstaller);
        var newOffice = HasOffice(newInstaller);
        var explicitSwitch = oldOffice != newOffice;
        var feedFolder = Path.GetDirectoryName(newInstaller)!;
        var workingFeed = Directory.CreateDirectory(Path.Combine(evidence, "isolated-feed")).FullName;
        var original = InstalledExe(oldVersion);
        var upgraded = InstalledExe(newVersion);
        await Run(oldInstaller, "/S");
        await InspectInstall(original, oldInstaller, oldOffice);
        var export = Path.Combine(evidence, "preserved-export.txt");
        await File.WriteAllTextAsync(export, "synthetic export");
        var storage = new LocalState(Settings);
        var exerciseUi = Environment.GetEnvironmentVariable("TABRILO_TEST_UPDATE_UI") == "1";
        storage.Write(new Preferences { Appearance = "Dark", UseTray = false, CheckUpdatesOnStartup = exerciseUi,
            Recent = [new("Synthetic result", export, DateTimeOffset.Now)] });

        if (explicitSwitch)
        {
            await Run(newInstaller, "/S");
            Console.WriteLine("Explicit newer-version edition change by manual Setup.");
        }
        else
        {
            foreach (var name in new[] { "appcast.xml", "appcast.xml.signature" })
                File.Copy(Path.Combine(feedFolder, name), Path.Combine(workingFeed, name));
            var setup = Path.Combine(workingFeed, "setup.exe");
            await File.WriteAllBytesAsync(setup, new byte[128]);
            await Exercise(false);
            File.Copy(newInstaller, setup, true);
            using (var file = File.Open(setup, FileMode.Open, FileAccess.ReadWrite, FileShare.None))
            {
                file.Position = file.Length - 1;
                var last = file.ReadByte();
                file.Position--;
                file.WriteByte((byte)(last ^ 1));
            }
            await Exercise(false);
            File.Copy(newInstaller, setup, true);
            if (exerciseUi) await InstalledUpdateUi.Run(original, upgraded, workingFeed);
            else await Exercise(true);
            File.Delete(setup);

            async Task Exercise(bool success)
            {
                var start = new ProcessStartInfo(original) { UseShellExecute = false };
                start.ArgumentList.Add("--exercise-installed-update");
                start.ArgumentList.Add(workingFeed);
                using var process = Process.Start(start) ?? throw new IOException("Could not launch installed application.");
                using var timeout = new CancellationTokenSource(TimeSpan.FromMinutes(10));
                await process.WaitForExitAsync(timeout.Token);
                var errorFile = Path.Combine(workingFeed, "update-error.txt");
                if (success && process.ExitCode != 0 && File.Exists(errorFile)) Console.WriteLine(File.ReadAllText(errorFile));
                Require(process.ExitCode == (success ? 0 : 1), "installed updater exit status");
                if (!success)
                {
                    Require(File.Exists(errorFile) && File.ReadAllText(errorFile).StartsWith("InvalidDataException:") &&
                        File.Exists(original) && !File.Exists(upgraded), "refusal preserved old installation");
                    File.Delete(errorFile);
                }
            }
        }
        await InspectInstall(upgraded, newInstaller, newOffice);
        Require(storage.Read() is { Appearance: "Dark", Recent.Length: 1 }, "update preserved preferences and history");
        await Run(Path.Combine(Path.GetDirectoryName(upgraded)!, "Uninstall.exe"), "/S");
        var elapsed = Stopwatch.StartNew();
        while ((File.Exists(upgraded) || File.Exists(original)) && elapsed.Elapsed < TimeSpan.FromSeconds(30))
            await Task.Delay(100);
        Require(!File.Exists(upgraded) && !File.Exists(original) && storage.Read().Appearance == "Dark" &&
            File.ReadAllText(export) == "synthetic export", "uninstall preserved local state and exported file");
        // Only the fresh synthetic profile created above belongs to this run.
        File.Delete(Path.Combine(Settings, "preferences.json"));
        var downloads = Path.Combine(Settings, "Updates");
        if (Directory.Exists(downloads)) Directory.Delete(downloads);
        Directory.Delete(Settings);
    }

    private static bool HasOffice(string installer) => FileVersionInfo.GetVersionInfo(installer).FileDescription ==
        $"{identity} Windows x64 office installer";

    private static async Task InspectInstall(string exe, string setup, bool office)
    {
        var folder = Path.GetDirectoryName(exe)!;
        Require(File.Exists(exe) && InstallerVersion(exe) == InstallerVersion(setup) &&
            File.Exists(Path.Combine(folder, "hostfxr.dll")), "installed version and self-contained runtime");
        ReportSize(setup, folder);
        await Run(exe, "--self-check");
        var qpdf = Path.Combine(folder, "tools", "qpdf", "qpdf.exe");
        await Run(qpdf, "--version");
        var engine = Path.Combine(folder, "tools", "office", "program", "soffice.com");
        Require(File.Exists(engine) == office, "installed edition matches Setup");
        if (!office) return;
        Require(new FileInfo(setup).Length > (300L << 20), "actual Office payload exceeds former update limit");
        var pdf = new Tabrilo.Processing.Pdfs(qpdf);
        var renderer = new Tabrilo.Processing.OfficeRenderer(engine, pdf);
        foreach (var extension in new[] { "docx", "pptx" })
            await renderer.RenderAsync(Path.GetFullPath("tests/fixtures/layout." + extension), async path =>
            {
                using var document = await pdf.OpenForRenderingAsync(path, null, default);
                Require(document.PageCount == 2, "installed Office layout page count");
                await Tabrilo.Processing.Pdfs.RenderPageAsync(document, 2, 96, Tabrilo.Processing.ImageFormat.Png, default);
                return path;
            }, default);
        Console.WriteLine("Installed Office rendered page two of both fixtures.");
    }
    private static bool IsTestInstaller(string path) => File.Exists(path) &&
        Path.GetFileName(path).StartsWith("Tabrilo-Isolated-", StringComparison.Ordinal) &&
        FileVersionInfo.GetVersionInfo(path).ProductName == "Tabrilo";

    private static Version InstallerVersion(string path)
    {
        var parts = FileVersionInfo.GetVersionInfo(path);
        return new Version(parts.ProductMajorPart, parts.ProductMinorPart, parts.ProductBuildPart);
    }

    private static string InstalledExe(Version version) => Path.Combine(Install, "versions", version.ToString(3), "Tabrilo.exe");

    private static void ReportSize(string installer, string folder)
    {
        var bytes = new DirectoryInfo(folder).EnumerateFiles("*", SearchOption.AllDirectories).Sum(file => file.Length);
        Console.WriteLine($"Installed {InstallerVersion(installer)}: {bytes} file bytes including uninstaller. Setup: {new FileInfo(installer).Length} bytes.");
    }

    private static async Task Run(string exe, string argument)
    {
        var start = new ProcessStartInfo(exe) { UseShellExecute = false, CreateNoWindow = true };
        start.ArgumentList.Add(argument);
        using var process = Process.Start(start) ?? throw new IOException("Could not start the installer test process.");
        await Wait(process);
    }

    private static async Task Wait(Process process)
    {
        using var timeout = new CancellationTokenSource(TimeSpan.FromMinutes(3));
        await process.WaitForExitAsync(timeout.Token);
        Require(process.ExitCode == 0, $"process {process.Id} exited {process.ExitCode}");
    }

    private static void Require(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException(message);
    }
}
