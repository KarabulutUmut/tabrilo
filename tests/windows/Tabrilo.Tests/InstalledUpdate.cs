using System.Diagnostics;
using System.IO;
using System.Net.Http;
using System.Security.Cryptography;
using System.Text;
using Chaos.NaCl;
using Microsoft.Win32;
using Tabrilo.Core;
using Tabrilo.Windows;

internal static class InstalledUpdate
{
    private static readonly string Install = Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Programs", "Tabrilo-Isolated");
    private static readonly string Settings = Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Tabrilo-Isolated");

    public static async Task RunAsync(string oldInstaller, string newInstaller, string evidence)
    {
        if (!IsTestInstaller(oldInstaller) || !IsTestInstaller(newInstaller))
            throw new ArgumentException("Use separate installers generated by package.ps1 -IsolatedTest.");
        if (Registry.GetValue(@"HKEY_CURRENT_USER\Software\Tabrilo-Isolated", "Version", null) is not null)
            throw new InvalidOperationException("Remove the existing Tabrilo-Isolated test installation first.");
        if (Directory.Exists(Settings) || Directory.Exists(Install))
            throw new InvalidOperationException("Use a fresh isolated test profile.");
        var oldVersion = InstallerVersion(oldInstaller);
        var newVersion = InstallerVersion(newInstaller);
        if (newVersion <= oldVersion) throw new ArgumentException("The new installer must upgrade the old version.");

        var seed = RandomNumberGenerator.GetBytes(32);
        Ed25519.KeyPairFromSeed(out var publicKey, out var privateKey, seed);
        try
        {
            var data = await File.ReadAllBytesAsync(newInstaller);
            var payloadSignature = Convert.ToBase64String(Ed25519.Sign(data, privateKey));
            const string origin = "https://tabrilo-install-test.invalid";
            var feed = Encoding.UTF8.GetBytes($"""
                <rss xmlns:sparkle="http://www.andymatuschak.org/xml-namespaces/sparkle"><channel><item>
                  <sparkle:channel>isolated-test</sparkle:channel><sparkle:minimumSystemVersion>10.0.19041</sparkle:minimumSystemVersion>
                  <enclosure url="{origin}/setup.exe" length="{data.Length}" sparkle:os="windows-x64"
                    sparkle:version="{newVersion}" sparkle:edSignature="{payloadSignature}" />
                </item></channel></rss>
                """);
            var signature = Encoding.ASCII.GetBytes(Convert.ToBase64String(Ed25519.Sign(feed, privateKey)));
            var channel = new UpdateChannel(1, "isolated-test", "windows-x64", origin + "/appcast.xml", origin,
                Convert.ToBase64String(publicKey));
            var system = Environment.OSVersion.Version;

            await Run(oldInstaller, "/S");
            var original = InstalledExe(oldVersion);
            Require(File.Exists(original) && File.Exists(Path.Combine(Path.GetDirectoryName(original)!, "hostfxr.dll")),
                "per-user old installation with the self-contained runtime");
            var installedFolder = Path.GetDirectoryName(original)!;
            ReportSize(oldInstaller, installedFolder);
            var engine = Path.Combine(installedFolder, "tools", "office", "program", "soffice.com");
            if (File.Exists(engine))
            {
                var pdf = new Tabrilo.Processing.Pdfs(Path.Combine(installedFolder, "tools", "qpdf", "qpdf.exe"));
                var renderer = new Tabrilo.Processing.OfficeRenderer(engine, pdf);
                foreach (var ext in new[] { "docx", "pptx" })
                {
                    await renderer.RenderAsync(Path.GetFullPath("tests/fixtures/layout." + ext), async path =>
                    {
                        using var document = await pdf.OpenForRenderingAsync(path, null, default);
                        Require(document.PageCount == 2, "installed Office layout page count");
                        await Tabrilo.Processing.Pdfs.RenderPageAsync(document, 2, 96, Tabrilo.Processing.ImageFormat.Png, default);
                        return path;
                    }, default);
                }
                Console.WriteLine("Installed Office engine rendered both two-page fixtures, including page two.");
            }
            var export = Path.Combine(evidence, "preserved-export.txt");
            await File.WriteAllTextAsync(export, "synthetic export");
            var storage = new LocalState(Settings);
            storage.Write(new Preferences { Appearance = "Dark", Recent = [new("Synthetic result", export, DateTimeOffset.Now)] });

            using (var interrupted = new Updates(channel, oldVersion, system, TestResponses(data[..128])))
            {
                var candidate = await interrupted.CheckAsync(default) ?? throw new InvalidOperationException("Expected upgrade");
                await Reject(() => interrupted.DownloadAsync(candidate, evidence, default));
                Require(File.Exists(original) && !File.Exists(InstalledExe(newVersion)), "interrupted download preserved old install");
            }
            data[^1] ^= 1;
            try
            {
                using var damaged = new Updates(channel, oldVersion, system, TestResponses(data));
                var candidate = await damaged.CheckAsync(default) ?? throw new InvalidOperationException("Expected upgrade");
                await Reject(() => damaged.DownloadAsync(candidate, evidence, default));
                Require(File.Exists(original) && !File.Exists(InstalledExe(newVersion)), "invalid payload left installation unchanged");
            }
            finally { data[^1] ^= 1; }

            using (var trusted = new Updates(channel, oldVersion, system, TestResponses(data)))
            {
                var candidate = await trusted.CheckAsync(default) ?? throw new InvalidOperationException("Expected upgrade");
                var setup = await trusted.DownloadAsync(candidate, evidence, default);
                try
                {
                    using var upgrade = trusted.StartInstaller(candidate, setup, unattendedTest: true);
                    await Wait(upgrade);
                }
                finally { File.Delete(setup); }
            }
            var upgraded = InstalledExe(newVersion);
            ReportSize(newInstaller, Path.GetDirectoryName(upgraded)!);
            Require(File.Exists(upgraded) && InstallerVersion(upgraded) == newVersion, "installed signed upgrade");
            var qpdf = Path.Combine(Path.GetDirectoryName(upgraded)!, "tools", "qpdf", "qpdf.exe");
            await Run(qpdf, "--version");
            await Run(upgraded, "--self-check");
            Require(storage.Read() is { Appearance: "Dark", Recent.Length: 1 }, "update preserved preferences and history");

            var uninstall = Path.Combine(Path.GetDirectoryName(upgraded)!, "Uninstall.exe");
            await Run(uninstall, "/S");
            var elapsed = Stopwatch.StartNew();
            while ((File.Exists(upgraded) || File.Exists(original)) && elapsed.Elapsed < TimeSpan.FromSeconds(20))
                await Task.Delay(100);
            Require(!File.Exists(upgraded) && !File.Exists(original) && !File.Exists(engine) && storage.Read().Appearance == "Dark" &&
                File.ReadAllText(export) == "synthetic export", "uninstall preserved local state and exported file");
            Console.WriteLine($"Installed and removed isolated versions {oldVersion} and {newVersion} (signed test upgrade).");

            HttpMessageHandler TestResponses(byte[] payload) => new Responses(new Dictionary<string, byte[]>
            {
                ["/appcast.xml"] = feed, ["/appcast.xml.signature"] = signature, ["/setup.exe"] = payload
            });
        }
        finally { CryptographicOperations.ZeroMemory(seed); CryptographicOperations.ZeroMemory(privateKey); }
    }

    private static bool IsTestInstaller(string path) => File.Exists(path) &&
        Path.GetFileName(path).StartsWith("Tabrilo-Isolated-", StringComparison.Ordinal) &&
        FileVersionInfo.GetVersionInfo(path).ProductName == "Tabrilo";

    private static Version InstallerVersion(string path)
    {
        var parts = FileVersionInfo.GetVersionInfo(path);
        return new Version(parts.ProductMajorPart, parts.ProductMinorPart, parts.ProductBuildPart);
    }

    private static string InstalledExe(Version version) => Path.Combine(Install, "versions", version.ToString(3), "Tabrilo.exe");

    private static void ReportSize(string installer, string folder)
    {
        var bytes = new DirectoryInfo(folder).EnumerateFiles("*", SearchOption.AllDirectories).Sum(file => file.Length);
        Console.WriteLine($"Installed {InstallerVersion(installer)}: {bytes} file bytes including uninstaller. Setup: {new FileInfo(installer).Length} bytes.");
    }

    private static async Task Run(string exe, string argument)
    {
        var start = new ProcessStartInfo(exe) { UseShellExecute = false, CreateNoWindow = true };
        start.ArgumentList.Add(argument);
        using var process = Process.Start(start) ?? throw new IOException("Could not start the installer test process.");
        await Wait(process);
    }

    private static async Task Wait(Process process)
    {
        using var timeout = new CancellationTokenSource(TimeSpan.FromMinutes(3));
        await process.WaitForExitAsync(timeout.Token);
        Require(process.ExitCode == 0, $"process {process.Id} exited {process.ExitCode}");
    }

    private static async Task Reject(Func<Task> action)
    {
        try { await action(); }
        catch (InvalidDataException) { return; }
        throw new InvalidOperationException("The untrusted update was accepted.");
    }

    private static void Require(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException(message);
    }
}
